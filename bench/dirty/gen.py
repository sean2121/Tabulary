#!/usr/bin/env python3
"""Generate the "dirty retail" benchmark database: a small Japanese-style order system with abbreviated names,
undocumented code values, logical-delete flags and no foreign keys. Deterministic (fixed seed).

Writes db/init/02_retail.sql (schema + data, loaded by the demo Postgres on first start) when run with --sql,
and prints the gold answers for bench/dirty/questions.yaml when run with --gold (needs the database loaded).

Business rules that exist only in people's heads (and must reach the LLM through Tabulary's review):
  m_kokyaku.kbn        1 = individual, 2 = corporate
  t_juchu.stat         10 = ordered, 20 = shipped, 90 = cancelled
  t_juchu.del_flg      '1' = logically deleted, must be excluded from everything
  t_nyukin.hoho_kbn    1 = cash, 2 = bank transfer, 3 = card
  sales                sum(t_juchu_mei.suryo * t_juchu_mei.tanka) over shipped (stat 20), non-deleted orders; payments are NOT sales
  t_juchu.kokyaku_cd   -> m_kokyaku.kokyaku_id (no foreign key, different column names)
  t_juchu.tanto_cd     -> m_tanto.tanto_cd;  t_juchu_mei.shohin_cd -> m_shohin.shohin_cd;  t_nyukin.juchu_no -> t_juchu.juchu_no
"""
from __future__ import annotations

import argparse
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
rnd = random.Random(20261115)

SURNAMES = ["佐藤", "鈴木", "高橋", "田中", "伊藤", "渡辺", "山本", "中村", "小林", "加藤", "吉田", "山田", "佐々木", "山口", "松本"]
GIVEN = ["太郎", "花子", "健", "美咲", "翔", "陽子", "大輔", "恵", "拓也", "由美"]
CORP = ["青井商事", "北山工業", "東都物産", "西川電機", "南海製作所", "中央印刷", "丸山建設", "大和運輸", "桜井食品", "三ツ星貿易", "光陽システム", "新星ホールディングス"]
PRODUCTS = [("S001", "コピー用紙 A4 500枚", "P", 450), ("S002", "コピー用紙 A3 500枚", "P", 900), ("S003", "トナーカートリッジ 黒", "P", 8000),
            ("S004", "トナーカートリッジ カラー", "P", 12000), ("S005", "ボールペン 黒 10本", "P", 600), ("S006", "付箋 75mm 5冊", "P", 380),
            ("S007", "クリアファイル 100枚", "P", 1200), ("S008", "デスクチェア", "F", 24000), ("S009", "スチールデスク", "F", 38000),
            ("S010", "キャビネット 3段", "F", 29000), ("S011", "ノートPC 14型", "E", 128000), ("S012", "モニター 27型", "E", 32000),
            ("S013", "無線マウス", "E", 2800), ("S014", "USBハブ 4ポート", "E", 1900), ("S015", "シュレッダー", "E", 18000)]
STAFF = [("T01", "岡本 直樹", "B1"), ("T02", "長谷川 真", "B1"), ("T03", "藤井 沙織", "B2"), ("T04", "村上 亮", "B2"), ("T05", "石田 奈々", "B3")]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def build() -> tuple[list[str], dict]:
    L = ["-- Dirty retail demo: abbreviated names, undocumented codes, logical deletes, no foreign keys. Generated by bench/dirty/gen.py.",
         "CREATE TABLE m_kokyaku (kokyaku_id integer PRIMARY KEY, kokyaku_nm varchar(60) NOT NULL, kbn char(1) NOT NULL, toroku_dt date NOT NULL, tel varchar(20), addr varchar(100));",
         "CREATE TABLE m_shohin (shohin_cd char(4) PRIMARY KEY, shohin_nm varchar(60) NOT NULL, ctg_cd char(1) NOT NULL, tanka_std numeric(10,0) NOT NULL);",
         "CREATE TABLE m_tanto (tanto_cd char(3) PRIMARY KEY, tanto_nm varchar(40) NOT NULL, bsho_cd char(2) NOT NULL);",
         "CREATE TABLE t_juchu (juchu_no char(7) PRIMARY KEY, kokyaku_cd integer NOT NULL, tanto_cd char(3) NOT NULL, juchu_dt date NOT NULL, stat char(2) NOT NULL, del_flg char(1) NOT NULL DEFAULT '0', biko varchar(200));",
         "CREATE TABLE t_juchu_mei (juchu_no char(7) NOT NULL, gyo_no smallint NOT NULL, shohin_cd char(4) NOT NULL, suryo integer NOT NULL, tanka numeric(10,0) NOT NULL, PRIMARY KEY (juchu_no, gyo_no));",
         "CREATE TABLE t_nyukin (nyukin_id serial PRIMARY KEY, juchu_no char(7) NOT NULL, kingaku numeric(12,0) NOT NULL, nyukin_dt date NOT NULL, hoho_kbn char(1) NOT NULL);",
         ""]
    customers = []
    for i in range(1, 41):
        corp = i % 3 == 0  # 13 corporate, 27 individual
        name = CORP[(i // 3 - 1) % len(CORP)] + ("" if i // 3 <= len(CORP) else f" {i}") if corp else f"{rnd.choice(SURNAMES)} {rnd.choice(GIVEN)}"
        if corp:
            name = ("株式会社" if i % 2 else "") + name + ("" if i % 2 else "株式会社")
        reg = date(2021, 1, 1) + timedelta(days=rnd.randint(0, 1600))
        customers.append((100 + i, name, "2" if corp else "1", reg))
        L.append(f"INSERT INTO m_kokyaku VALUES ({100 + i}, {q(name)}, '{'2' if corp else '1'}', '{reg}', '0{rnd.randint(3, 9)}-{rnd.randint(1000, 9999)}-{rnd.randint(1000, 9999)}', NULL);")
    for p in PRODUCTS:
        L.append(f"INSERT INTO m_shohin VALUES ({q(p[0])}, {q(p[1])}, '{p[2]}', {p[3]});")
    for s in STAFF:
        L.append(f"INSERT INTO m_tanto VALUES ({q(s[0])}, {q(s[1])}, '{s[2]}');")
    orders, lines, pays = [], [], []
    n = 0
    for _ in range(320):
        n += 1
        no = f"J{n:06d}"
        c = rnd.choice(customers)
        corp = c[2] == "2"
        d = date(2025, 1, 1) + timedelta(days=rnd.randint(0, 699))  # 2025-01-01 .. 2026-11-30
        r = rnd.random()
        stat = "90" if r < 0.08 else ("10" if r < 0.20 else "20")
        if d > date(2026, 10, 15) and stat == "20" and rnd.random() < 0.5:
            stat = "10"
        delf = "1" if rnd.random() < 0.05 else "0"
        tanto = rnd.choice(STAFF)[0]
        orders.append((no, c[0], tanto, d, stat, delf))
        L.append(f"INSERT INTO t_juchu VALUES ({q(no)}, {c[0]}, {q(tanto)}, '{d}', '{stat}', '{delf}', NULL);")
        total = 0
        for g in range(1, rnd.randint(1, 4) + 1):
            p = rnd.choice(PRODUCTS)
            qty = rnd.randint(1, 3) if p[2] in "FE" else rnd.randint(1, 60)
            if corp:
                qty = qty * rnd.randint(1, 3)
            price = p[3] if rnd.random() < 0.6 else int(p[3] * rnd.choice([0.9, 0.95, 0.85]))
            lines.append((no, g, p[0], qty, price))
            total += qty * price
            L.append(f"INSERT INTO t_juchu_mei VALUES ({q(no)}, {g}, {q(p[0])}, {qty}, {price});")
        if stat == "20" and delf == "0" and rnd.random() < 0.85:
            paid = total if rnd.random() < 0.8 else int(total * 0.5)
            pd = d + timedelta(days=rnd.randint(5, 45))
            pays.append((no, paid, pd, "2" if corp else rnd.choice("123")))
            L.append(f"INSERT INTO t_nyukin (juchu_no, kingaku, nyukin_dt, hoho_kbn) VALUES ({q(no)}, {paid}, '{pd}', '{pays[-1][3]}');")
    return L, {"customers": customers, "orders": orders, "lines": lines, "pays": pays}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--sql", action="store_true", help="write db/init/02_retail.sql")
    a = ap.parse_args()
    L, _ = build()
    if a.sql:
        out = ROOT / "db" / "init" / "02_retail.sql"
        out.write_text("\\connect postgres\nCREATE DATABASE retail;\n\\connect retail\n" + "\n".join(L) + "\n")
        print(f"wrote {out} ({len(L)} statements)")
